import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, username: string) {
  await page.goto('/acceso')
  await page.getByLabel('Usuario', { exact: true }).fill(username)
  await page.getByLabel('Contraseña', { exact: true }).fill('Cuyes-local-test-123!')
  await page.getByRole('button', { name: 'Ingresar', exact: true }).click()
  await page.waitForURL(url => !url.pathname.startsWith('/acceso'))
}
async function order(page: Page, id: string) {
  await page.goto(`/cuyes/ventas?orden=${id}`)
  await expect(page.getByRole('heading', { name: /^Orden CUY-/ })).toBeVisible()
}
async function reason(page: Page, value = 'Hecho ficticio verificado en prueba aislada') {
  await page.getByLabel('Motivo de la acción', { exact: true }).fill(value)
}
async function pay(page: Page) {
  await page.getByLabel('Comprobante privado (PDF/JPEG/PNG, hasta 5 MiB)').setInputFiles({
    name: 'test-voucher.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n% ficticio\n%%EOF'),
  })
  await page.getByRole('button', { name: 'Cargar comprobante privado', exact: true }).click()
  await expect(page.getByText('Comprobante privado cargado; todavía no valida el pago.')).toBeVisible()
  await reason(page)
  await page.getByLabel('Referencia de pago o ajuste', { exact: true }).fill('PAGO-FICTICIO')
  await page.getByRole('button', { name: 'Validar pago manual por importe acordado' }).click()
  await expect(page.getByText('Estado: PAGADO', { exact: true })).toBeVisible()
}
async function prepare(page: Page) {
  await page.getByRole('button', { name: 'Sugerir FIFO' }).click()
  await expect(page.getByLabel('Cantidad efectiva prevista').first()).toBeVisible()
  await page.getByLabel('Motivo de preparación', { exact: true }).fill('Seleccionado y comprobado en las pozas')
  await page.getByRole('button', { name: 'Guardar selección sin retirar inventario' }).click()
  await expect(page.getByRole('heading', { name: 'Detalle vigente y conformidades' })).toBeVisible()
  await reason(page)
  await page.getByRole('button', { name: 'Dar conformidad de mis galpones sobre este detalle' }).click()
  await expect(page.getByText(/GALPONERO · galpón/)).toBeVisible()
}

test('módulo con PIN y carne por peso con conductor, contra Django y PostgreSQL', async ({ browser, page }) => {
  await login(page, 'vilma')
  await page.goto('/cuyes/ventas')
  await page.getByText('Nueva orden de venta', { exact: true }).click()
  await page.getByLabel('Centro de la venta', { exact: true }).selectOption(process.env.SITRAP_TEST_CENTER!)
  await page.getByLabel('Nombre del cliente', { exact: true }).fill('Cliente ficticio módulo')
  await page.getByLabel('Tipo de ítem', { exact: true }).selectOption('MODULO')
  await page.getByLabel('Módulo', { exact: true }).selectOption(process.env.SITRAP_TEST_MODULE!)
  await page.getByLabel('Precio acordado por módulo').fill('100.00')
  await page.getByLabel('Motivo de solicitud', { exact: true }).fill('Solicitud ficticia módulo')
  await page.getByRole('button', { name: 'Solicitar venta (todavía sin reserva)' }).click()
  await expect(page.getByRole('heading', { name: /^Orden CUY-/ })).toBeVisible()
  const directId = new URL(page.url()).searchParams.get('orden')!

  const workerContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const worker = await workerContext.newPage()
  await login(worker, 'galponero')
  await order(worker, directId)
  await reason(worker)
  await worker.getByRole('button', { name: 'Confirmar disponibilidad y reservar todo' }).click()
  await expect(worker.getByText(/Reserva: IMPAGA/)).toBeVisible()
  await order(page, directId)
  await pay(page)
  await reason(page)
  await page.getByRole('button', { name: 'Generar o regenerar PIN (invalida el anterior)' }).click()
  const ticket = await page.getByText(/PIN de una sola entrega:/).innerText()
  const pin = ticket.match(/\b\d{8}\b/)![0]

  await order(worker, directId)
  await prepare(worker)
  await worker.getByLabel('Quién realiza físicamente la entrega').fill('Galponero ficticio')
  await worker.getByLabel('Referencia de conformidad del cliente / entrega').fill('Retiro ficticio acreditado')
  await worker.getByLabel('PIN presentado por el cliente').fill(pin)
  await worker.getByRole('button', { name: 'Validar PIN, retirar inventario y entregar al cliente' }).click()
  await expect(worker.getByText('Estado: ENTREGADO', { exact: true })).toBeVisible()
  let balance = await worker.request.get(`/api/v1/cuyes/pens/${process.env.SITRAP_TEST_PEN}`)
  expect((await balance.json()).population).toBe(24)
  await expect(worker.getByRole('heading', { name: 'Trazabilidad del retiro efectivo' })).toBeVisible()

  await page.goto('/cuyes/ventas')
  await page.getByText('Nueva orden de venta', { exact: true }).click()
  await page.getByLabel('Centro de la venta', { exact: true }).selectOption(process.env.SITRAP_TEST_CENTER!)
  await page.getByLabel('Nombre del cliente', { exact: true }).fill('Cliente ficticio carne')
  await page.getByLabel('Modalidad', { exact: true }).selectOption('PUNTO')
  await page.getByLabel('Punto de venta', { exact: true }).selectOption(process.env.SITRAP_TEST_POINT!)
  await page.getByLabel('Tipo de ítem', { exact: true }).selectOption('PESO')
  await page.getByLabel('Calidad acordada', { exact: true }).selectOption('A')
  await page.getByLabel('Número de animales a reservar y retirar').fill('2')
  await page.getByLabel('Peso acordado para cobrar (KG, 3 decimales)').fill('2.500')
  await page.getByLabel('Precio acordado por KG').fill('20.00')
  await page.getByLabel('Motivo de solicitud', { exact: true }).fill('Carne por peso ficticia')
  await page.getByRole('button', { name: 'Solicitar venta (todavía sin reserva)' }).click()
  await expect(page.getByRole('heading', { name: /^Orden CUY-/ })).toBeVisible()
  const transportId = new URL(page.url()).searchParams.get('orden')!
  await order(worker, transportId); await reason(worker)
  await worker.getByRole('button', { name: 'Confirmar disponibilidad y reservar todo' }).click()
  await expect(worker.getByText(/Reserva: IMPAGA/)).toBeVisible()
  await order(page, transportId); await pay(page)
  await reason(page)
  await page.getByLabel('Conductor autorizado', { exact: true }).selectOption(process.env.SITRAP_TEST_DRIVER!)
  await page.getByRole('button', { name: 'Asignar conductor y activar viaje' }).click()
  await expect(page.getByText('Operación aceptada por el servidor.', { exact: true })).toBeVisible()
  await order(worker, transportId); await prepare(worker)

  const driverContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const driver = await driverContext.newPage()
  await login(driver, 'driver-sale')
  const list = await driver.request.get('/api/v1/cuyes/sales/orders?workspace=TRANSPORTE')
  const visible = (await list.json()).results
  expect(visible).toHaveLength(1)
  expect(visible[0].id).toBe(transportId)
  expect(visible[0].total).toBeUndefined()
  await order(driver, transportId)
  await reason(driver)
  await driver.getByRole('button', { name: 'Estoy conforme con las cantidades a recoger' }).click()
  await expect(driver.getByText(/CONDUCTOR · galpón/)).toBeVisible()
  await order(worker, transportId); await reason(worker)
  await worker.getByRole('button', { name: 'Confirmar salida física (descuenta una sola vez)' }).click()
  await expect(worker.getByText('Estado: EN_RUTA', { exact: true })).toBeVisible()
  balance = await worker.request.get(`/api/v1/cuyes/pens/${process.env.SITRAP_TEST_PEN}`)
  expect((await balance.json()).population).toBe(22)
  await order(driver, transportId); await reason(driver)
  await driver.getByLabel('Quién realiza físicamente la entrega').fill('Conductor ficticio')
  await driver.getByLabel('Referencia de conformidad del cliente / entrega').fill('Dejado a encargado ficticio')
  await driver.getByRole('button', { name: 'Confirmar llegada al punto de venta' }).click()
  await expect(driver.getByText('Estado: EN_PUNTO', { exact: true })).toBeVisible()
  await order(page, transportId); await reason(page)
  await page.getByLabel('Quién realiza físicamente la entrega').fill('Encargado ficticio del punto')
  await page.getByLabel('Referencia de conformidad del cliente / entrega').fill('Retiro posterior ficticio acreditado')
  await page.getByRole('button', { name: 'Registrar retiro posterior del cliente' }).click()
  await expect(page.getByText('Estado: ENTREGADO', { exact: true })).toBeVisible()
  balance = await worker.request.get(`/api/v1/cuyes/pens/${process.env.SITRAP_TEST_PEN}`)
  expect((await balance.json()).population).toBe(22)
  await workerContext.close(); await driverContext.close()
})
